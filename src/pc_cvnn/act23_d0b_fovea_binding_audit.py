"""Read-only audit: can the persisted HexFovea bind a self-moved finger region?

Only the open RGB camera frame reaches the frozen Fovea at inference.  Training targets are the
separate camera difference generated by the agent's own gripper pulse.  Simulator geometry is
loaded only after prediction to score the selected saccade.
"""
from __future__ import annotations

import argparse
import json
import os
import pickle
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

GRID = np.asarray([(72.0, 72.0), (120.0, 72.0), (168.0, 72.0),
                   (72.0, 120.0), (120.0, 120.0), (168.0, 120.0),
                   (72.0, 168.0), (120.0, 168.0), (168.0, 168.0)])


def _truth(path: Path) -> dict[int, list[float] | None]:
    return {int(r["pose_id"]): r["truth_claw_px"]
            for r in (json.loads(line) for line in path.read_text(encoding="utf-8").splitlines())}


def _motion_colour(image: np.ndarray, motion: np.ndarray) -> np.ndarray:
    weights = motion.astype(float)
    return (image.astype(float) * weights[..., None]).sum(axis=(0, 1)) / (weights.sum() + 1e-12) / 255.0


def _motion_at(motion: np.ndarray, gaze: np.ndarray, radius: float = 24.0) -> float:
    yy, xx = np.mgrid[:motion.shape[0], :motion.shape[1]]
    inside = (xx - gaze[0]) ** 2 + (yy - gaze[1]) ** 2 <= radius ** 2
    return float(motion[inside].sum() / (motion.sum() + 1e-12))


def _features(template: bytes, image: np.ndarray, target_rgb: np.ndarray) -> np.ndarray:
    """Each pose gets a pristine frozen Fovea copy; no dynamic state crosses a split boundary."""
    fovea = pickle.loads(template)
    fovea.z = 1.0
    rows = []
    for gaze in GRID:
        fovea.step_id(image, gaze, target_rgb, learn=False)
        top = np.asarray(fovea.net.node("top").mu)
        rows.append(np.concatenate([np.real(top), np.imag(top), [1.0]]))
    return np.asarray(rows)


def _fit(x: np.ndarray, y: np.ndarray, ridge: float = 1e-3):
    mean, scale = x.mean(0), x.std(0)
    scale[scale < 1e-9] = 1.0
    z = (x - mean) / scale
    weights = np.linalg.solve(z.T @ z + ridge * np.eye(z.shape[1]), z.T @ y)
    return mean, scale, weights


def run(state: Path, frames: Path, evaluation: Path, output: Path, limit: int | None = None):
    os.environ["ACT23_D0_FREEZE"] = "1"
    with state.open("rb") as handle:
        template = pickle.dumps(pickle.load(handle)["fovea"])
    data = np.load(frames)
    n = len(data["pose_id"]) if limit is None else min(limit, len(data["pose_id"]))
    ids, images, motions = data["pose_id"][:n].astype(int), data["open_rgb"][:n], data["motion_rgb_l1"][:n]
    features = np.asarray([_features(template, image, _motion_colour(image, motion))
                           for image, motion in zip(images, motions)])
    targets = np.asarray([[_motion_at(motion, gaze) for gaze in GRID] for motion in motions])
    test = ids % 3 == 0
    x_train, y_train = features[~test].reshape(-1, features.shape[-1]), targets[~test].reshape(-1)
    mean, scale, weights = _fit(x_train, y_train)
    scores = ((features - mean) / scale) @ weights
    truth = _truth(evaluation)
    records, errors, baseline_errors = [], [], []
    for i, pose_id in enumerate(ids):
        if not test[i]:
            continue
        choice = int(np.argmax(scores[i]))
        selected, expected = GRID[choice].tolist(), truth.get(int(pose_id))
        err = None if expected is None else float(np.linalg.norm(np.subtract(selected, expected)))
        base_err = None if expected is None else float(np.linalg.norm(np.subtract(GRID[4], expected)))
        if err is not None:
            errors.append(err); baseline_errors.append(base_err)
        records.append({"schema": "act23-d0b-fovea-binding-prediction-v1", "pose_id": int(pose_id),
                        "selected_gaze_px": selected, "truth_claw_px": expected, "error_px": err,
                        "centre_baseline_error_px": base_err,
                        "self_motion_score": float(targets[i, choice]),
                        "scores": [float(x) for x in scores[i]]})
    output.mkdir(parents=True, exist_ok=True)
    with (output / "predictions.jsonl").open("w", encoding="utf-8") as handle:
        for row in records:
            handle.write(json.dumps(row, sort_keys=True) + "\n")
    result = {"schema": "act23-d0b-fovea-binding-result-v1", "frozen": True,
              "poses": int(n), "train_poses": int((~test).sum()), "test_poses": int(test.sum()),
              "paired_test_poses": len(errors),
              "median_error_px": None if not errors else float(np.median(errors)),
              "centre_baseline_median_error_px": None if not baseline_errors else float(np.median(baseline_errors)),
              "within_24px": int(sum(e <= 24.0 for e in errors)),
              "frames": str(frames), "evaluation": str(evaluation), "state": str(state)}
    (output / "result.json").write_text(json.dumps(result, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return result


def main():
    parser = argparse.ArgumentParser(description="Read-only D0b Fovea self-motion binding audit")
    parser.add_argument("--state", type=Path, required=True)
    parser.add_argument("--frames", type=Path, required=True)
    parser.add_argument("--evaluation", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--limit", type=int)
    args = parser.parse_args()
    print(json.dumps(run(args.state, args.frames, args.evaluation, args.output, args.limit), indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
